#!/usr/bin/env bash
# Prints THIRD_PARTY_NOTICES.md: the licenses of every module the release
# binary links on any of its targets (goreleaser builds linux, darwin and
# windows; windows links a few modules the others do not). Linux first, then
# what each other GOOS adds. `mise run notices` writes it; `mise run
# notices:check` (CI) diffs it. No versions or versioned URLs, so a Renovate
# bump only touches this file when it adds a module or changes a license.
set -euo pipefail
cd "$(dirname "$0")/.."
self=github.com/nonchan7720/kubeglance

# report GOOS TEMPLATE [--ignore MODULE ...]
report() {
  local goos=$1 tpl=$2
  shift 2
  GOOS=$goos GOARCH=amd64 go-licenses report . --ignore "$self" "$@" --template "$tpl" 2>/dev/null
}

# modules already covered, as --ignore flags for the next GOOS
seen=()
ignores() { for m in "${seen[@]}"; do printf -- '--ignore\n%s\n' "$m"; done; }

cat <<'HEADER'
# Third-party notices

kubeglance is licensed under the Apache License 2.0 (see [LICENSE](LICENSE)). Its release binaries and image include the Go modules below; their licenses follow.

This file is generated by `mise run notices` (go-licenses, for every release GOOS) from the modules the binary links. Do not edit it by hand: CI fails when it is not current. Versions are left out on purpose, so a dependency bump changes this file only when the set of modules or a license changes; `go.mod` has the versions.

| module | license |
|---|---|
HEADER

rows="" sections=""
for goos in linux darwin windows; do
  mapfile -t flags < <(ignores)
  rows+=$(report "$goos" scripts/notices/row.tpl "${flags[@]}")$'\n'
  sections+=$(report "$goos" scripts/notices/section.tpl "${flags[@]}")$'\n'
  while IFS=, read -r name _; do seen+=("$name"); done < <(GOOS=$goos GOARCH=amd64 go-licenses report . --ignore "$self" "${flags[@]}" 2>/dev/null)
done
printf '%s' "$rows" | sed '/^$/d'
printf '%s' "$sections"
